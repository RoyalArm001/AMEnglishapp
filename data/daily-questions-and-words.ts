export function getDailyWordsChallenge(
  date: string,
  level: CEFRLevel = 'A1',
  count: number = 3
): DailyWordChallengeState {
  let seed = 0;
  for (let i = 0; i < date.length; i++) {
    seed = (seed * 31 + date.charCodeAt(i)) % 100000;
  }

  const matchingLevel = DAILY_WORDS_POOL.filter((w) => w.level === level);
  const pool = matchingLevel.length >= count ? matchingLevel : DAILY_WORDS_POOL;

  const selected: DailyWordItem[] = [];
  const poolCopy = [...pool];
  for (let i = 0; i < count && poolCopy.length > 0; i++) {
    const idx = (seed + i * 7) % poolCopy.length;
    selected.push(poolCopy[idx]);
    poolCopy.splice(idx, 1);
  }

  return {
    id: `dw-${date}`,
    userId: 'user-main',
    date,
    isCompleted: false,
    completedCount: 0,
    currentWordIndex: 0,
    totalTarget: count,
    words: selected,
    updatedAt: Date.now(),
  };
}

export function getDailyQuestionsDayState(
  date: string,
  level: CEFRLevel = 'A1',
  profession?: string,
  count: number = 10
): DailyQuestionDayState {
  let seed = 0;
  for (let i = 0; i < date.length; i++) {
    seed = (seed * 37 + date.charCodeAt(i)) % 100000;
  }

  let pool = DAILY_QUESTIONS_POOL.filter((q) => q.level === level);
  if (profession) {
    const profMatch = pool.filter((q) => q.professions?.includes(profession as any));
    if (profMatch.length >= 3) {
      pool = [...profMatch, ...pool.filter((q) => !q.professions?.includes(profession as any))];
    }
  }
  if (pool.length < count) {
    pool = DAILY_QUESTIONS_POOL;
  }

  const selected: DailyQuestionItem[] = [];
  const poolCopy = [...pool];
  for (let i = 0; i < count && poolCopy.length > 0; i++) {
    const idx = (seed + i * 11) % poolCopy.length;
    selected.push(poolCopy[idx]);
    poolCopy.splice(idx, 1);
  }

  return {
    id: `dq-${date}`,
    userId: 'user-main',
    date,
    totalQuestions: selected.length,
    currentIndex: 0,
    isCompleted: false,
    score: 0,
    questions: selected,
    answers: [],
    updatedAt: Date.now(),
  };
}

